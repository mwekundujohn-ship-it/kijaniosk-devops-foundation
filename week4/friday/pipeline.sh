#!/usr/bin/env bash
#
# KijaniKiosk Week 4 pipeline.
#
#   pipeline.sh [cloud|multipass]
#
# Runs Terraform, extracts the resulting server IPs, writes them to the
# Ansible inventory, then runs the playbook. Exits non-zero if any stage fails.
#
# Path modes:
#   cloud      (default here) servers on AWS EC2; IPs come from Terraform outputs
#   multipass  servers as Multipass VMs; IPs come from `multipass info`
#
set -euo pipefail

export PATH="${HOME}/.local/share/pipx/venvs/ansible/bin:${HOME}/.local/bin:${PATH}"

MODE="${1:-cloud}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TF_DIR="${SCRIPT_DIR}/terraform"
ANSIBLE_DIR="${SCRIPT_DIR}/ansible"
INVENTORY="${ANSIBLE_DIR}/inventory.ini"
KEY_PATH="${HOME}/.ssh/kijaniosk_ed25519"

log() { printf '\n=== %s ===\n' "$*"; }

# --- 1. Terraform -------------------------------------------------------
log "terraform init"
terraform -chdir="${TF_DIR}" init -input=false

log "terraform apply"
terraform -chdir="${TF_DIR}" apply -input=false -auto-approve

# --- 2. Build the Ansible inventory from live outputs -------------------
log "building ${INVENTORY} (mode: ${MODE})"

resolve_ip() {
  local role="$1" host="$2"
  if [ "${MODE}" = "multipass" ]; then
    multipass info "${host}" | awk '/IPv4/{print $2; exit}'
  else
    terraform -chdir="${TF_DIR}" output -raw "${role}_server_ip"
  fi
}

{
  echo "# AUTO-GENERATED by pipeline.sh - do not edit by hand."
  echo "# Mode: ${MODE}. Regenerate by re-running: ./pipeline.sh ${MODE}"
  echo "[kijaniosk]"
  for entry in "api:kijaniosk-api" "payments:kijaniosk-payments" "logs:kijaniosk-logs"; do
    role="${entry%%:*}"
    host="${entry##*:}"
    ip="$(resolve_ip "${role}" "${host}")"
    if [ -z "${ip}" ]; then
      echo "ERROR: could not resolve IP for ${host}" >&2
      exit 1
    fi
    printf '%-20s ansible_host=%s\n' "${host}" "${ip}"
  done
} > "${INVENTORY}"

cat "${INVENTORY}"

# --- 3. Ansible ---------------------------------------------------------
log "ansible-playbook"
ansible-playbook -i "${INVENTORY}" "${ANSIBLE_DIR}/kijaniosk.yml"

log "pipeline complete"
